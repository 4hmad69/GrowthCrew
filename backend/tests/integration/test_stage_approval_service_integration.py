# --- concurrency ---------------------------------------------------------------


def _interleaved_approval(
    settings: Settings,
    workspace_id: UUID,
    version: int,
    *,
    winner: Callable[[Any, UUID], None],
) -> StageApproval:
    """Run approve() on one session while another "wins the race" mid-flight.

    Wraps the first approval lookup of the racing service so that, right
    after it reports that no approval exists, the winner callback commits
    a competing approval from a second session. The racing service then
    inserts its own row and hits the unique constraint - the exact
    interleaving of two simultaneous requests, made deterministic.
    """

    database_a = Database.from_settings(settings)
    database_b = Database.from_settings(settings)
    try:
        with database_a.session() as session_a, database_b.session() as session_b:
            service = StageApprovalService(session_a)
            repository = service._approvals
            original = repository.get_by_workspace_and_stage
            raced = {"done": False}

            def racing(workspace: UUID, stage: str) -> StageApproval | None:
                result = original(workspace, stage)
                if not raced["done"]:
                    raced["done"] = True
                    winner(session_b, workspace)
                return result

            repository.get_by_workspace_and_stage = racing  # type: ignore[method-assign]
            return service.approve(workspace_id, MR, version)
    finally:
        database_a.dispose()
        database_b.dispose()


def test_two_simultaneous_approvals_of_the_same_record_settle_to_one(
    context: Context, workspace: UUID
) -> None:
    """If another request approves the same record first, this one returns that approval."""

    version = _version(context, workspace, MR)

    def winner(session: Any, workspace_id: UUID) -> None:
        StageApprovalService(session).approve(workspace_id, MR, version)

    result = _interleaved_approval(context.settings, workspace, version, winner=winner)

    rows = _approval_rows(context.settings, workspace)
    assert len(rows) == 1
    assert result.id == rows[0].id
    assert rows[0].approved_version == version


def test_a_race_lost_to_a_different_approval_is_reported_as_a_conflict(
    context: Context, workspace: UUID
) -> None:
    """If what won the race is not an approval of this record, say so instead of guessing."""

    version = _version(context, workspace, MR)

    def winner(session: Any, workspace_id: UUID) -> None:
        session.add(
            StageApproval(
                workspace_id=workspace_id,
                stage=MR.value,
                record_id=uuid4(),
                approved_version=version + 40,
            )
        )
        session.commit()

    with pytest.raises(ResourceConflictError) as caught:
        _interleaved_approval(context.settings, workspace, version, winner=winner)

    assert str(caught.value) == (
        "The market research stage's approval was changed by another request. Try again."
    )
    assert len(_approval_rows(context.settings, workspace)) == 1


# --- cleanup of approvals with their workspace ----------------------------------


def test_deleting_the_workspace_removes_its_approvals(context: Context) -> None:
    """Approvals must not outlive the workspace they belong to."""

    workspace_id = _new_workspace(context, "Approval Cascade Co", generate=True)
    try:
        for stage in STAGES[:3]:
            _approve(context, workspace_id, stage)
        assert len(_approval_rows(context.settings, workspace_id)) == 3
    finally:
        _cleanup(context.settings, workspace_id)

    database = Database.from_settings(context.settings)
    try:
        with database.session() as session:
            remaining = session.scalar(
                select(func.count())
                .select_from(StageApproval)
                .where(StageApproval.workspace_id == workspace_id)
            )
    finally:
        database.dispose()

    assert remaining == 0
