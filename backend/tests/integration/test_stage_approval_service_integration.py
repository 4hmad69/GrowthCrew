"""Real PostgreSQL integration tests for the stage approval service.

Uses the deterministic "local" LLM and embeddings providers and no
Tavily key, so this file is about the approval rules against real stage
records and a real database, not about model quality. Each test gets a
workspace whose seven stages were generated by a real full-strategy run,
so every approval is pinned to a genuine record id and version.

The properties that only a real database can prove are the point:

- an approval retires itself when its stage record changes, including
  the trap where a deleted-and-regenerated stage restarts at the same
  version number and only its new record id tells it apart;
- approving never touches the stage record it approves;
- the unique constraint turns two simultaneous approvals into one
  approval, deterministically simulated by interleaving two sessions.

HTTP routes for approval arrive in a later commit and are tested with
the rest of the API; this file calls the service directly.
"""

