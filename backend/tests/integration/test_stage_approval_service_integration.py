def test_a_deleted_and_regenerated_stage_at_the_same_version_is_not_approved(
    context: Context, workspace: UUID
) -> None:
    """Regenerating from scratch restarts at version 1; only the record id differs.

    This is the trap that matching on version alone would fall into: the
    new record has the very version number that was approved, but it is
    different content nobody has reviewed.
    """

    approved = _approve(context, workspace, MR)
    assert approved.approved_version == 1

    _delete_market_research(context.settings, workspace)
    regenerated = context.client.post(context.url(workspace, "market-research"), json={})
    assert regenerated.status_code in {200, 201}

    stage = _by_stage(_status(context, workspace))[MR.value]
    assert stage["version"] == 1
    assert stage["approval"] == "draft"
    assert _market_research_record(context.settings, workspace).id != approved.record_id


def test_approving_a_recreated_stage_replaces_the_orphaned_approval(
    context: Context, workspace: UUID
) -> None:
    """The leftover row from the deleted record is reused, not accumulated."""

    first = _approve(context, workspace, MR)
    _delete_market_research(context.settings, workspace)
    context.client.post(context.url(workspace, "market-research"), json={})

    second = _approve(context, workspace, MR)

    rows = _approval_rows(context.settings, workspace)
    assert len(rows) == 1
    assert second.id == first.id
    assert rows[0].record_id != first.record_id
    assert _by_stage(_status(context, workspace))[MR.value]["approval"] == "approved"


